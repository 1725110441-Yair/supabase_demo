CREATE TABLE IF NOT EXISTS conctactos(
    id_contacto INT AUTOINCREMENT PRIMARY KEY, 
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    telefono VARCHAR(13) NOT NULL,
);

